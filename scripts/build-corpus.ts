/**
 * Build step: mgc-task-pack/docs/*.md  →  lib/corpus.generated.ts
 *
 * Runs in `predev` / `prebuild`. Emitting a TypeScript module rather than
 * reading files at request time means no filesystem access in the serverless
 * handler, and the corpus is type-checked with the rest of the app.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import type { DocId, Section } from "../lib/types.js";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Document-level metadata.
 *
 * `effectiveDate` and `version` are transcribed from each document's own front
 * matter — "Effective 1 April 2025", "Version 2.1, updated May 2025". They are
 * load-bearing: conflict resolution (lib/conflicts.ts) uses them to say which of
 * two contradicting claims is more recent. Transcribing rather than parsing
 * because there are three documents and three prose formats; a regex here would
 * be more code and more fragile than the table.
 */
const DOCS: {
  id: DocId;
  file: string;
  title: string;
  effectiveDate: string;
  version: string;
}[] = [
  {
    id: "brochure",
    file: "01_mgc_aurora_heights_brochure.md",
    title: "MGC Aurora Heights — Project Brochure",
    effectiveDate: "2025-03-01",
    version: "Issued March 2025",
  },
  {
    id: "price-list",
    file: "02_price_list_payment_plan.md",
    title: "Price List & Payment Plan",
    effectiveDate: "2025-04-01",
    version: "Effective 1 April 2025",
  },
  {
    id: "booking-policy",
    file: "03_booking_policy_faq.md",
    title: "Booking Policy & Sales FAQ",
    effectiveDate: "2025-05-01",
    version: "v2.1",
  },
];

/** "Other Charges" → "other-charges", for stable citation keys. */
function slugify(heading: string): string {
  return heading
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/**
 * Split on `##` headings. Level-2 is the natural semantic unit in all three
 * documents — "Location Premiums", "Transfers", "Cancellations and Refunds" —
 * so each section is self-contained enough to cite on its own.
 *
 * Content before the first `##` (title + front matter) is emitted as an
 * "Overview" section rather than dropped: the brochure's issue date and the
 * price list's "supersedes the January 2025 list" line live there.
 */
function splitSections(
  markdown: string,
  doc: (typeof DOCS)[number],
): Section[] {
  const lines = markdown.split(/\r?\n/);
  const sections: Section[] = [];

  let heading = "Overview";
  let buffer: string[] = [];

  const flush = () => {
    const text = buffer.join("\n").trim();
    if (!text) return;
    sections.push({
      id: `${doc.id}#${slugify(heading)}`,
      docId: doc.id,
      docTitle: doc.title,
      heading,
      text,
      effectiveDate: doc.effectiveDate,
      version: doc.version,
    });
    buffer = [];
  };

  for (const line of lines) {
    const match = /^##\s+(.*)$/.exec(line);
    if (match) {
      flush();
      heading = match[1].trim();
    } else {
      buffer.push(line);
    }
  }
  flush();

  return sections;
}

const sections: Section[] = DOCS.flatMap((doc) =>
  splitSections(
    readFileSync(join(ROOT, "mgc-task-pack", "docs", doc.file), "utf8"),
    doc,
  ),
);

const out = `// GENERATED by scripts/build-corpus.ts — do not edit by hand.
// Regenerate with: npm run build-corpus
import type { Section } from "./types";

export const CORPUS: Section[] = ${JSON.stringify(sections, null, 2)};

export const SECTION_BY_ID = new Map(CORPUS.map((s) => [s.id, s]));
`;

mkdirSync(join(ROOT, "lib"), { recursive: true });
writeFileSync(join(ROOT, "lib", "corpus.generated.ts"), out, "utf8");

console.log(
  `[build-corpus] ${sections.length} sections from ${DOCS.length} documents ` +
    `(${sections.reduce((n, s) => n + s.text.length, 0)} chars)`,
);
